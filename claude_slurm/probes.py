"""Probe scripts that try to break each boundary and report PASS/FAIL."""
from __future__ import annotations

import shlex

from .paths import CONFIG_ROOT, HOME, PREFIX

_LIB = r'''
pass=0; fail=0; warn=0
ok()   { echo "PASS  $*"; pass=$((pass+1)); }
bad()  { echo "FAIL  $*"; fail=$((fail+1)); }
note() { echo "WARN  $*"; warn=$((warn+1)); }
can_write() {  # dirs: try creating a file; files: open for append, write nothing
  if [[ -d "$1" ]]; then local f="$1/.cs-probe-$$"
    if ( : > "$f" ) 2>/dev/null; then rm -f "$f"; return 0; fi; return 1
  fi
  ( : >> "$1" ) 2>/dev/null
}
expect_write()   { if can_write "$1"; then ok "can write $1"; else bad "cannot write $1 (expected writable)"; fi; }
expect_nowrite() { [[ -e "$1" ]] || { ok "$1 not present"; return; }
                   if can_write "$1"; then bad "could write $1"; else ok "cannot write $1"; fi; }
expect_absent()  { if [[ -e "$1" ]]; then bad "$1 is visible"; else ok "$1 not visible"; fi; }
summary() { echo; echo "== $pass passed, $fail failed, $warn warnings"; [[ $fail -eq 0 ]]; }
'''


def login_probe(pol: dict) -> str:
    q = shlex.quote
    proj = pol["project"]
    lines = ["#!/bin/bash",
             "# Run *inside* claude-hpc by asking Claude: `bash .slurm/login-probe.sh`",
             "# Every line should be PASS. Generated by `claude-slurm check --login-probe`.",
             _LIB,
             f"cd {q(proj)}",
             'echo "== filesystem"',
             f"expect_write {q(proj)}",
             f"expect_nowrite {q(str(HOME))}",
             f"expect_nowrite {q(str(CONFIG_ROOT))}",
             f"expect_nowrite {q(str(PREFIX))}",
             f"expect_nowrite {q(str(pol['image']['path']))}",
             f"expect_nowrite {q(pol['logs_dir'])}",
             'if mkdir -p .claude/.cs-probe 2>/dev/null; then rmdir .claude/.cs-probe; '
             'bad "could write .claude/"; else ok "cannot write .claude/"; fi',
             'if [[ -e .mcp.json ]]; then expect_nowrite .mcp.json; '
             'elif ( : > .mcp.json ) 2>/dev/null; then rm -f .mcp.json; bad "could create .mcp.json"; '
             'else ok "cannot create .mcp.json"; fi',
             'parent=$(dirname "$PWD")',
             ]
    extra = pol["login"]["extra_write"]
    lines.append(f'case "$parent" in {"|".join(q(e) for e in extra) or "__none__"}) ;; '
                 '*) expect_nowrite "$parent" ;; esac')
    for d in pol["login"]["deny_read"]:
        d2 = d.replace("~", "$HOME", 1) if d.startswith("~") else q(d)
        # Claude's sandbox hides a directory by mounting an empty one over it.
        lines.append(f'if [[ -e {d2} ]]; then if {{ [[ -d {d2} ]] && [[ -n "$(ls -A {d2} 2>/dev/null)" ]] '
                     f'|| {{ [[ -f {d2} ]] && head -c1 {d2} >/dev/null 2>&1; }}; }}; '
                     f'then bad "can read {d}"; else ok "cannot read {d}"; fi; fi')
    lines += [
        'echo "== slurm (all must fail)"',
        'for c in "sbatch --test-only --wrap=true -t 1" "squeue -h -u $USER" "scontrol ping"; do',
        # Slurm clients retry an unreachable slurmctld for minutes.
        '  if out=$(timeout 15 $c 2>&1); then bad "$c reached slurmctld"; '
        'else ok "$c failed: $(head -c 100 <<<"$out" | tr "\\n" " ")"; fi',
        'done',
        'if command -v munge >/dev/null; then if timeout 15 munge -n >/dev/null 2>&1; then '
        'bad "munge credential could be created"; else ok "munge blocked"; fi; fi',
        'for s in /run/user/$(id -u)/claude-slurm/*.sock; do [[ -e $s ]] || continue',
        '  if python3 -c "import socket,sys; socket.socket(socket.AF_UNIX).connect(sys.argv[1])" '
        '"$s" 2>/dev/null; then bad "can connect to service socket $s"; '
        'else ok "service socket $s unreachable"; fi',
        'done',
        'echo "== network"',
        'if command -v curl >/dev/null; then '
        'if curl -sS -m 8 -o /dev/null https://example.com 2>/dev/null; then '
        'note "example.com reachable (fine only if you allowed it)"; '
        'else ok "unlisted domain blocked"; fi; fi',
        'summary',
    ]
    return "\n".join(lines) + "\n"


def service_probe(pol: dict) -> str:
    """The login probe plus service-only checks; run as a service by `check --service`."""
    body = login_probe(pol).rsplit("summary\n", 1)[0]
    body = body.replace("# Run *inside* claude-hpc by asking Claude: `bash .slurm/login-probe.sh`",
                        "# Run as a service by `claude-slurm check --service`.")
    # bwrap can only block a path by mounting over it, which would leave an empty
    # .mcp.json in the project. claude-hpc ignores project .mcp.json files.
    body = body.replace('bad "could create .mcp.json"',
                        'note "could create .mcp.json (claude-hpc ignores it)"')
    return body + "\n".join([
        'echo "== service sandbox"',
        'if systemd-run --user /bin/true >/dev/null 2>&1; then bad "systemd-run --user works"; '
        'else ok "systemd-run --user blocked"; fi',
        'if systemctl --user is-system-running >/dev/null 2>&1; then bad "systemctl --user works"; '
        'else ok "systemctl --user blocked"; fi',
        'expect_absent "/run/user/$(id -u)/bus"',
        "expect_absent /run/dbus/system_bus_socket",
        "expect_absent /run/docker.sock",
        "expect_absent /run/munge/munge.socket.2",
        'if curl -sS -m 8 -o /dev/null https://pypi.org 2>/dev/null; then bad "network reachable"; '
        'else ok "no network (even allowed domains)"; fi',
        'if out=$(cs-slurm list --json 2>&1); then ok "cs-slurm list works"; '
        'else bad "cs-slurm list failed: $out"; fi',
        'if cs-run cs-probe-not-a-command >/dev/null 2>&1; then bad "cs-run accepted an unknown command"; '
        'else ok "cs-run refuses unknown commands"; fi',
        "summary",
    ]) + "\n"


_MOUNT_SCAN = r'''
echo "== host filesystem mounts visible in the container"
while read -r mp fstype src; do
  mp=$(printf '%b' "${mp//\\/\\0}")   # mountinfo escapes: \040 -> space
  case "$fstype" in
    proc|sysfs|devpts|devtmpfs|tmpfs|mqueue|cgroup|cgroup2|overlay|squashfs|fuse.squashfuse*|hugetlbfs|securityfs|debugfs|tracefs|pstore|bpf|configfs|fusectl|autofs|binfmt_misc) continue ;;
  esac
  expected=0
  for e in "${EXPECTED[@]}"; do
    [[ "$mp" == "$e" || "$mp" == "$e"/* ]] && expected=1
  done
  case "$mp" in
    /etc/hosts|/etc/resolv.conf|/etc/localtime|/etc/hostname|/etc/passwd|/etc/group) expected=1 ;;
    /.singularity.d*|*nvidia*|*cuda*|/var/run/nvidia-persistenced*|/run/nvidia-persistenced*) expected=1 ;;
  esac
  if [[ $expected -eq 1 ]]; then echo "      $mp ($fstype)"; else note "unexpected host mount: $mp ($fstype from $src)"; fi
done < <(awk '{for(i=7;i<=NF;i++) if($i=="-"){print $5, $(i+1), $(i+2); break}}' /proc/self/mountinfo)
'''


def job_probe(pol: dict) -> str:
    q = shlex.quote
    mount = pol["project_mount"]
    expected = [mount] + [b["container"] for b in pol["binds"]]
    lines = ["#!/bin/bash",
             "# Runs inside the container via the broker. Generated by claude-slurm check --job.",
             _LIB,
             'echo "== identity: $(id)"; echo "HOME=$HOME  PWD=$PWD"',
             "EXPECTED=(" + " ".join(q(e) for e in expected) + ")",
             'echo "== mounts"',
             f"expect_write {q(mount)}"]
    for b in pol["binds"]:
        if b["mode"] == "rw":
            lines.append(f"expect_write {q(b['container'])}")
        else:
            lines.append(f"if can_write {q(b['container'])}; then bad 'ro bind {b['container']} is writable'; "
                         f"else ok 'ro bind {b['container']} is read-only'; fi")
    lines += [
        'echo "== host paths that must not be visible"',
        f"expect_absent {q(str(HOME) + '/.ssh')}",
        f"expect_absent {q(str(CONFIG_ROOT))}",
        f"expect_absent {q(pol['logs_dir'])}",
        f"expect_absent {q(pol['project'] + '/.slurm') if pol['project'] != mount else '/nonexistent-cs'}",
        "expect_absent /var/run/munge/munge.socket.2",
        "expect_absent /run/munge/munge.socket.2",
        'if command -v sbatch >/dev/null; then note "sbatch binary present in image (harmless without munge)"; fi',
        # Apptainer itself sets *_BIND inside the container to the --bind list,
        # so only flag entries that aren't in the policy.
        "ALLOWED_SRC=(" + " ".join(q(s) for s in [pol["project"]] + [b["host"] for b in pol["binds"]]) + ")",
        'for __b in $(printf "%s,%s" "${APPTAINER_BIND:-}" "${SINGULARITY_BIND:-}" | tr "," " "); do',
        '  __s=${__b%%:*}; __hit=0',
        '  for __a in "${ALLOWED_SRC[@]}"; do [[ $__s == "$__a" ]] && __hit=1; done',
        '  if [[ $__hit -eq 0 ]]; then bad "unexpected bind in container env: $__b"; fi',
        'done',
        _MOUNT_SCAN,
        'echo "== env"; env | sort | grep -E "^(SLURM_|CUDA_|CS_PROBE)" || true',
        'summary',
    ]
    return "\n".join(lines) + "\n"
